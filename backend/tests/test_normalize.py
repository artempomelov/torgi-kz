def test_clean_address():
    from torgi.normalize import clean_address, valid_cadastral

    assert clean_address("Область Жетісу, УСТАРЕВШЕЕ - г.Текели, г.Текели п.Рудничный ул. Ескелди Би д.24 кв.7") == (
        "Область Жетісу, г.Текели, г.Текели п.Рудничный ул. Ескелди Би д.24 кв.7")
    assert clean_address("г.Шымкент, УСТАРЕВШЕЕ - г.Шымкент - Каратауский район, квартал 222, участок 58") == (
        "г.Шымкент, Каратауский район, квартал 222, участок 58")
    assert clean_address("Область Абай, УСТАРЕВШЕЕ - Кокпектинский район, Кокпектинский район, село Бигаш") == (
        "Область Абай, Кокпектинский район, село Бигаш")
    assert clean_address(
        "Туркестанская область, Шардаринский район, Шардара ауданы, Шардара қаласы,№55 көшесі бойынан"
    ) == "Туркестанская область, Шардаринский район"
    assert clean_address("г. Алматы, ул. Абая 10") == "г. Алматы, ул. Абая 10"
    assert valid_cadastral("111") is None and valid_cadastral("ааа") is None
    assert valid_cadastral("21-319-016-445") == "21-319-016-445"


def test_reconcile_place_districts_named_after_cities():
    """Районы с «городскими» названиями — не город и не область (реальные адреса из базы)."""
    from torgi.normalize import reconcile_place as rp

    # Алматинский район и район Алматы — это Астана
    assert rp("Астана", "Алматинская область", "г.Астана, Алматинский район, пр. Бауыржан Момышұлы 15/1") == ("Астана", "Астана")
    assert rp("Астана", "Астана", "г. Нур-Султан, район Алматы, ул.Темирбек Жургенов, дом 30") == ("Астана", "Астана")
    assert rp("Алматы", "Алматы", "г.Нур-Султан район Алматы, ул. Берен, дом №7") == ("Астана", "Астана")
    # Жетысуский район — это Алматы, а не Жетысуская область
    assert rp("Алматы", "Жетысуская область", "г.Алматы, Жетысуский р-он, мкр.Айнабулак д.152") == ("Алматы", "Алматы")
    # Балхашский район Алматинской области — не город Балхаш
    assert rp("Балхаш", "Алматинская область", "Алматинская обл, Балхашский р-н, Коктальский с/о") == (None, "Алматинская область")
    # село Жанаозен в Абайской области — не город в Мангистау
    assert rp("Жанаозен", "Абайская область", "Абайская обл, Жарминский район, с. Жанаозен") == (None, "Абайская область")
    # трасса Алматы–Ташкент в Туркестанской области — не Алматы
    assert rp("Туркестан", "Туркестанская область",
              "Туркестанская область, Казыгуртский район, вдоль трассы Алматы–Ташкент") == (None, "Туркестанская область")
    # улица Петропавловская — не город
    assert rp(None, None, "г. Семей, ул. Петропавловская, 5") == ("Семей", "Абайская область")
    # карточка источника ошиблась городом — верим адресу
    assert rp("Актау", "Мангистауская область", "г. Алматы, Ауэзовский р-н, мкр. Аксай-4, д.87") == ("Алматы", "Алматы")
    # старая область до реформы 2022 года — регион по городу
    assert rp("Талдыкорган", "Алматинская область", "Алматинская обл, Талдыкорган, мкр. Самал, д. 10 Б") == (
        "Талдыкорган", "Жетысуская область")
    assert rp("Алматы", "Алматинская область", "Алматинская обл., г.Капшагай, 5 мкр.") == ("Конаев", "Алматинская область")
    # в адресе нет ни города, ни области — оставляем как у источника
    assert rp("Астана", "Акмолинская область", "Земельный участок в границах Максимовского с.о.") == (
        "Астана", "Акмолинская область")


def test_canonical_district():
    from torgi.normalize import canonical_district as cd

    assert cd("район Медеу", "Алматы") == cd("Медеуский район", "Алматы") == cd("район Медеуский", "Алматы") == "Медеуский район"
    assert cd("Бостандыский район", "Алматы") == "Бостандыкский район"  # опечатка источника
    assert cd("Алматинский район", "Астана") == cd("район Алматы", "Астана") == "район Алматы"
    assert cd("Нұра район", "Астана") == cd("район Нура", "Астана") == "район Нура"
    assert cd("район Байконур", "Астана") == cd("район Байконыр", "Астана") == "район Байконыр"
    assert cd("Тұран район", "Шымкент") == "Туранский район"
    assert cd("район Казыбекби", "Караганда") == "район имени Казыбек би"
    assert cd("район Алматы", "Алматы") is None and cd("Нур-Султан район", "Астана") is None
    assert cd("район Хобдинский", "Актобе") == "Хобдинский район"


def test_real_price_history_drops_typos():
    from types import SimpleNamespace as P
    pts = [P(price=161_222_746), P(price=None), P(price=16_122_746), P(price=15_000_000)]
    assert [p.price for p in nz.real_price_history(pts)] == [16_122_746, 15_000_000]
    pts = [P(price=30_000_000), P(price=27_000_000)]
    assert [p.price for p in nz.real_price_history(pts)] == [30_000_000, 27_000_000]


