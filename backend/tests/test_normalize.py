    (("Абайская обл, Семей, Мәңгілік ел, д. 10",), "Семей", "Абайская область"),
    (("ЗКО, г. Уральск ул. Соколиная д.9/1",), "Уральск", "Западно-Казахстанская область"),
    (("Алматы, р-н Алмалы, ул. Кашгарская",), "Алматы", "Алматы"),
