def test_town_from_address_beats_source_city():
    # город из карточки источника — «Туркестан», а в адресе явно другой город области
    t = "Земельный участок по адресу:Туркестанская обл, Шардаринский р-н, г. Шардара, улица №55"
    assert nz.reconcile_place("Туркестан", "Туркестанская область", "Туркестанская область, Шардаринский район", t) \
        == ("Шардара", "Туркестанская область")
    assert nz.reconcile_place("Атырау", "Атырауская область", "Атырауская обл, Жылойский район, г. Кульсары, дом 55")[0] \
        == "Кульсары"
    # село в районе области — города нет, только область
    assert nz.reconcile_place("Тараз", "Жамбылская область", "Жамбылская область, Кордайский район, с. Отар.") \
        == (None, "Жамбылская область")
    # районы самого города — не сельские
    assert nz.reconcile_place("Караганда", "Карагандинская область",
                              "Карагандинская обл., г. Караганда, Октябрьский район, ул. Абая")[0] == "Караганда"
    assert nz.reconcile_place(None, None, "Алматы, Бостандыкский район, ул. Тимирязева 42") == ("Алматы", "Алматы")


def test_infer_district_from_microdistrict():
    """Район по микрорайону — для адресов без района (реальные адреса из базы и подзаголовки Крыши)."""
    inf = nz.infer_district

    assert inf("Алматы", "Алматы, мкр. Шугыла, ул. С. Жунисов, д. 10, к. 6, кв. 31") == "Наурызбайский район"
    assert inf("Алматы", "Алматы, 45, 64", "Однокомнатная квартира по адресу: г.Алматы, мкр. Аккент, д.45, кв.64") \
        == "Алатауский район"
    assert inf("Алматы", "Алматы / Калкаман-2 / 6-ая улица 23") == "Наурызбайский район"
    assert inf("Алматы", "г. Алматы, Шұғыла шағын ауданы, 10") == "Наурызбайский район"  # казахская форма
    assert inf("Алматы", "Алматы, мкр Карагайлы, уч. 727") == inf("Алматы", "мкр. Таусамалы, 5") == "Наурызбайский район"
    assert inf("Алматы", "Коммерческое помещение в г.Алматы, мкр.Аксай 2, дом 73А") == "Ауэзовский район"
    assert inf("Алматы", "г. Алматы, мкрн. Таугуль-2, д.38") == inf("Алматы", "г. Алматы, мкр. Мамыр") == "Ауэзовский район"
    assert inf("Алматы", "г. Алматы, мкр. Жетысу-3, д. 55А") == "Ауэзовский район"
    assert inf("Алматы", "Жилой дом. мкр Нурлытау (Энергетик, 2), д.110") == "Бостандыкский район"
    assert inf("Алматы", "Алматы, мкр.Орбита-3, 21, 17") == "Бостандыкский район"
    assert inf("Алматы", "г. Алматы, мкр. Самал-2, д. 5") == "Медеуский район"
    assert inf("Алматы", "г. Алматы, мкр. Айнабулак-3, д. 1") == "Жетысуский район"
    assert inf("Алматы", "г. Алматы, мкр. Жулдыз-1, д. 5") == "Турксибский район"
    # номерные микрорайоны 1–12 — Ауэзовский; «6-й градокомплекс» и «20-й» — Алатауский, их не трогаем
    assert inf("Алматы", "г. Алматы, мкр №8, д. 41") == inf("Алматы", "г. Алматы, 8 микрорайон, д. 41") == "Ауэзовский район"
    assert inf("Алматы", "г. Алматы, мкр 6-й градокомплекс, 5") is None
    assert inf("Алматы", "г. Алматы, мкр 20-й, 17") is None
    # «Алматы / Сарыарка /» — район между косыми чертами (BCC)
    assert inf("Астана", "Астана / Сарыарка / ул.Суворова, д. 23Б") == "район Сарыарка"
    assert inf("Алматы", "Алматы / Турксибский/ ул. Сейфуллина, д. 500/79") == "Турксибский район"
    assert inf("Астана", "Астана, мкр Уркер, ул. Укили Ыбырай 15") == "район Нура"
    # неоднозначные и чужие названия — не угадываем
    assert inf("Алматы", "г. Алматы, мкр. Тау Самал, 5") is None  # Медеу, но легко спутать с Таусамалы
    assert inf("Алматы", "Квартиры в ЖК «Жайлау»") is None  # ЖК, а не микрорайон
    assert inf("Алматы", "ул. Жетысу, д. 5") is None and inf("Алматы", "вдоль реки Аксай") is None
    assert inf("Талдыкорган", "Талдыкорган, мкр. Самал, д. 10 Б") is None  # только Алматы и Астана
    assert inf("Конаев", "Алматинская обл., г.Капшагай, 5 мкр.") is None
    assert inf(None, "мкр. Шугыла") is None


def test_lot_district_explicit_beats_microdistrict():
    from torgi.export import lot_district as ld

    # явный район из адреса не переписываем, даже если микрорайон по Крыше в другом районе
    assert ld("Алматы / Алатауский / мкр. Калкаман, ул. Актамберды Жырау, д.85", "Алматы") == "Алатауский район"
    assert ld("г.Алматы, Жетысуский р-он, мкр.Айнабулак д.152", "Алматы") == "Жетысуский район"
    assert ld("г. Алматы, Ауэзовский р-н, мкр. Аксай-4, д.87", "Алматы") == "Ауэзовский район"
    # явный район в заголовке важнее микрорайона в адресе
    assert ld("Алматы, мкр. Шугыла, 10", "Алматы", "Квартира, г. Алматы, Ауэзовский район, мкр. Шугыла") == "Ауэзовский район"
    assert ld("Алматы, мкр. Шугыла, 10", "Алматы") == "Наурызбайский район"
    # формы записи района, которые раньше терялись
    assert ld("г. Астана, р-он Сарыарка, ул. Кенесары, дом 4", "Астана") == "район Сарыарка"
    assert ld("Астана / район \"Сарыарка\" / ул.Косшыгулулы, д.6", "Астана") == "район Сарыарка"
    assert ld("г.Алматы, Медеуский р-он, ПК «Горный Гигант» участок 2283", "Алматы") == "Медеуский район"
    assert ld("Земельный участок, ИЖС в Наурызбайском районе г. Алматы", "Алматы") == "Наурызбайский район"
