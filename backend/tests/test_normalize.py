def test_lot_district_from_description():
    from torgi.export import lot_district as ld

    # BCC: в адресе пусто, район — только в описании
    assert ld(None, "Астана", None, "2-х комнатная квартира город Acтана, район Нұра, Е 535 ул, дом 4, кв.73") == "район Нура"
    assert ld("г.Астана, ул. Кенесары д.1 кв 333", "Астана", None,
              "Продается 2-х ком. квартира по адресу: город Астана, Сарыаркинский район, ул. Кенесары") == "район Сарыарка"
    # из описания — только официальные районы города: «район Мега» пропускаем и ищем дальше
    assert ld(None, "Алматы", None, "Удобный район Мега, рядом Бостандыкский район") == "Бостандыкский район"
    assert ld(None, "Алматы", None, "Тихий район Мега") is None
    assert ld(None, "Аксу", None, "Тихий район Мега") is None  # районов города не знаем — из описания не берём
    # явный район в описании важнее микрорайона в адресе
    assert ld("Алматы, мкр. Шугыла, 10", "Алматы", None, "Квартира в Ауэзовском районе") == "Ауэзовский район"
