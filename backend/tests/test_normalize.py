def test_street_named_after_person_is_not_city():
    assert nz.detect_city("Жамбылская область, Таласский район, г. Каратау, ул. Д. Конаева, 48") != "Конаев"
    assert nz.detect_city("с.Алтын Арық, ул.Конаева №29") is None
